CREATE DATABASE IF NOT EXISTS cd_horizonte CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE cd_horizonte;
CREATE TABLE IF NOT EXISTS admins (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL, email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS matches (
 id INT AUTO_INCREMENT PRIMARY KEY, opponent VARCHAR(120) NOT NULL, competition VARCHAR(120) NOT NULL,
 match_date DATETIME NOT NULL, venue VARCHAR(160) DEFAULT '', home_score INT NULL, away_score INT NULL,
 status ENUM('scheduled','live','half_time','finished','postponed') NOT NULL DEFAULT 'scheduled',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS gallery (
 id INT AUTO_INCREMENT PRIMARY KEY, title VARCHAR(160) NOT NULL, image_path VARCHAR(255) NOT NULL,
 display_order INT NOT NULL DEFAULT 0, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS players (
 id INT AUTO_INCREMENT PRIMARY KEY, full_name VARCHAR(120) NOT NULL, position VARCHAR(60) NOT NULL,
 shirt_number INT NULL, photo_path VARCHAR(255) DEFAULT NULL, bio TEXT, active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS news (
 id INT AUTO_INCREMENT PRIMARY KEY, title VARCHAR(200) NOT NULL, slug VARCHAR(220) NOT NULL UNIQUE,
 summary TEXT, body MEDIUMTEXT, image_path VARCHAR(255) DEFAULT NULL, published BOOLEAN NOT NULL DEFAULT FALSE,
 published_at DATETIME NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS products (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(160) NOT NULL, description TEXT,
 price DECIMAL(10,2) NOT NULL DEFAULT 0, image_path VARCHAR(255), stock INT NOT NULL DEFAULT 0,
 active BOOLEAN NOT NULL DEFAULT TRUE, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS memberships (
 id INT AUTO_INCREMENT PRIMARY KEY, full_name VARCHAR(150) NOT NULL, email VARCHAR(190) NOT NULL,
 phone VARCHAR(40), message TEXT, status ENUM('pending','approved','rejected') NOT NULL DEFAULT 'pending',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS contact_messages (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL, email VARCHAR(190) NOT NULL,
 subject VARCHAR(180), message TEXT NOT NULL, read_at DATETIME NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
